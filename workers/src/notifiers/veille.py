"""Daily "veille" recap email, rendered per recipient in their language.

The daily agent inserts articles through ``POST /articles/ingest`` and then calls
``POST /notify/veille`` with the article ids. This module builds one HTML email per
recipient (FR / EN / AR, RTL for Arabic) with a link to each article on the platform
and to its original source, and sends it through Resend.
"""
